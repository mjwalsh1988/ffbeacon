/**
 * How sharp the site's lines are allowed to be, on the relay's 0 to 1 dial.
 *
 * Lower than Discord's default of 0.8 on purpose. A Discord channel is a room
 * where people are already joking; this panel sits directly above the power
 * rankings on a page somebody opened to check their team. 0.55 keeps the
 * character and drops the lines that exist purely at a manager's expense.
 */
const SITE_SNARK = 0.55;

/* -------------------------------------------------------------------------- */
/* Entry point                                                                */
/* -------------------------------------------------------------------------- */

export function buildActivityCard(
  event: ActivityEvent,
  ctx: ActivityContext,
): ActivityCard {
  const voice = new Voice(event.id, SITE_SNARK);
  const base = emptyCard(event, ctx);

  switch (event.kind) {
    case "trade":
      return tradeCard(base, event, ctx, voice);
    case "waiver":
    case "free_agent":
    case "commissioner_move":
      // A commissioner-executed trade is stored two-sided, because a flat
      // adds/drops list cannot say which roster gave up which player. When the
      // payload has sides, it gets the two-column layout regardless of the word
      // Sleeper used for it.
      return Array.isArray(event.payload.sides)
        ? tradeCard(base, event, ctx, voice)
        : wireCard(base, event, ctx, voice);
    case "matchup_result":
      return resultCard(base, event, ctx, voice);
    case "lineup_change":
      return lineupCard(base, event, ctx, voice);
    case "reserve_move":
      return reserveCard(base, event, ctx);
    case "scoring_change":
      return scoringCard(base, event);
    case "roster_positions_change":
      return rosterSlotsCard(base, event);
    case "team_count_change":
      return teamCountCard(base, event);
    case "league_setting_change":
      return settingsCard(base, event);
    case "league_renamed":
      return renameCard(base, event);
    case "league_status_change":
      return statusCard(base, event);
    case "draft_status_change":
      return draftCard(base, event);
    case "manager_joined":
    case "manager_left":
      return managerCard(base, event, ctx);
    case "roster_owner_change":
      return ownerCard(base, event, ctx);
    case "commissioner_change":
      return commissionerCard(base, event);
    case "team_identity_change":
      return identityCard(base, event, ctx);
    default:
      return base;
  }
}

