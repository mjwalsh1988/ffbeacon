function tradeCard(
  base: ActivityCard,
  event: ActivityEvent,
  ctx: ActivityContext,
  voice: Voice,
): ActivityCard {
  const sides = readSides(event.payload);
  const columns: ActivityColumn[] = sides.map((side) => {
    const chip = chipFor(ctx, side.rosterId);
    const assets: ActivityAsset[] = [
      ...side.players.map((id) => playerAsset(ctx, id, "in")),
      ...side.picks.map((p) => pickAsset(p, "in")),
    ];
    return {
      // Just "Receives". The chip directly underneath carries the team's name
      // and avatar, and repeating it in the heading printed the same words
      // twice, one line apart, on every trade card.
      heading: "Receives",
      chip,
      assets,
      faab: side.faab > 0 ? `$${side.faab} FAAB` : null,
      score: null,
      tone: "neutral",
    };
  });

  const names = sides.map((s) => chipFor(ctx, s.rosterId).label);
  const pieceCount = sides.reduce(
    (n, s) => n + s.players.length + s.picks.length + (s.faab > 0 ? 1 : 0),
    0,
  );

  const byCommissioner = event.kind === "commissioner_move";

  return {
    ...base,
    accent: byCommissioner ? "slate" : "purple",
    icon: byCommissioner ? "gavel" : "trade",
    eyebrow: byCommissioner
      ? "Commissioner move"
      : sides.length > 2
        ? `${sides.length} team trade`
        : "Trade",
    title:
      names.length > 2
        ? `${listOf(names)} made a trade`
        : names.length === 2
          ? `${names[0]} traded with ${names[1]}`
          : "Trade",
    line: !byCommissioner && pieceCount > 0 ? voice.pick(TRADE_LINES) : null,
    chips: [],
    columns,
    href: transactionsHref(ctx, event),
    hrefLabel: "Open in transactions",
  };
}

