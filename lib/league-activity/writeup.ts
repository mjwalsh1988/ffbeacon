function resultCard(
  base: ActivityCard,
  event: ActivityEvent,
  ctx: ActivityContext,
  voice: Voice,
): ActivityCard {
  const p = event.payload as {
    sides?: Array<{ rosterId: number; points: number; benchPoints: number | null }>;
    margin?: number;
    tie?: boolean;
  };
  const sides = Array.isArray(p.sides) ? p.sides : [];
  if (sides.length !== 2) return base;

  const tie = Boolean(p.tie);
  const margin = Number(p.margin ?? 0);
  const [top, bottom] = sides;

  const topChip = { ...chipFor(ctx, top.rosterId), tone: tie ? ("tie" as const) : ("win" as const) };
  const bottomChip = {
    ...chipFor(ctx, bottom.rosterId),
    tone: tie ? ("tie" as const) : ("loss" as const),
  };

  const columns: ActivityColumn[] = [
    {
      heading: tie ? "Tied" : "Winner",
      chip: topChip,
      assets: [],
      faab: null,
      score: points(top.points),
      tone: tie ? "tie" : "win",
    },
    {
      heading: tie ? "Tied" : "Loser",
      chip: bottomChip,
      assets: [],
      faab: null,
      score: points(bottom.points),
      tone: tie ? "tie" : "loss",
    },
  ];

  const stats: ActivityStat[] = [
    {
      label: "Margin",
      value: tie ? "Tied" : points(margin),
      tone: "neutral",
    },
  ];
  // A null bench total is Sleeper sending no per-player points for that week.
  // Omitted rather than shown as zero, which would read as a claim.
  for (const side of sides) {
    if (side.benchPoints === null) continue;
    stats.push({
      label: `${chipFor(ctx, side.rosterId).label} bench`,
      value: points(side.benchPoints),
      tone:
        side.rosterId === bottom.rosterId && side.benchPoints > margin && !tie
          ? "bad"
          : "neutral",
    });
  }

  const loserBench = bottom.benchPoints;
  const benchCostTheGame = !tie && loserBench !== null && loserBench > margin;

  const line = tie
    ? null
    : benchCostTheGame
      ? voice.pick(BENCH_LINES)
      : margin >= 30
        ? voice.pick(BLOWOUT_LINES)
        : margin <= 5
          ? voice.pick(NAILBITER_LINES)
          : null;

  const title = tie
    ? `${topChip.label} and ${bottomChip.label} tied at ${points(top.points)}`
    : `${topChip.label} beat ${bottomChip.label}, ${points(top.points)} to ${points(bottom.points)}`;

  return {
    ...base,
    accent: "emerald",
    icon: "trophy",
    eyebrow: "Final score",
    title,
    line,
    chips: [],
    columns,
    stats,
    footnote: benchCostTheGame
      ? `${bottomChip.label} left ${points(loserBench as number)} on the bench, more than the ${points(margin)} they lost by.`
      : null,
    href: matchupHref(ctx, event, top.rosterId),
    hrefLabel: "Open this matchup",
  };
}

