function wireCard(
  base: ActivityCard,
  event: ActivityEvent,
  ctx: ActivityContext,
  voice: Voice,
): ActivityCard {
  const p = event.payload as {
    rosterId?: number | null;
    adds?: string[];
    drops?: string[];
    bid?: number | null;
  };
  const rosterId = typeof p.rosterId === "number" ? p.rosterId : null;
  const chip = rosterId != null ? chipFor(ctx, rosterId) : null;
  const adds = Array.isArray(p.adds) ? p.adds : [];
  const drops = Array.isArray(p.drops) ? p.drops : [];
  const bid = typeof p.bid === "number" && Number.isFinite(p.bid) ? p.bid : null;

  const moves: ActivityAsset[] = [
    ...adds.map((id) => playerAsset(ctx, id, "in")),
    ...drops.map((id) => playerAsset(ctx, id, "out")),
  ];

  const eyebrow =
    event.kind === "waiver"
      ? "Waiver claim"
      : event.kind === "free_agent"
        ? "Free agent move"
        : "Commissioner move";

  const who = chip?.label ?? "A team";
  const title =
    adds.length > 0 && drops.length > 0
      ? `${who} swapped ${listOf(adds.map((id) => playerName(ctx, id)))} in for ${listOf(
          drops.map((id) => playerName(ctx, id)),
        )}`
      : adds.length > 0
        ? `${who} added ${listOf(adds.map((id) => playerName(ctx, id)))}`
        : drops.length > 0
          ? `${who} dropped ${listOf(drops.map((id) => playerName(ctx, id)))}`
          : `${who} made a move`;

  const stats: ActivityStat[] = [];
  if (bid !== null) {
    stats.push({
      label: "Winning bid",
      value: bid > 0 ? `$${bid}` : "Free",
      tone: "neutral",
    });
  }

  return {
    ...base,
    accent: event.kind === "commissioner_move" ? "slate" : "cyan",
    icon:
      event.kind === "waiver"
        ? "waiver"
        : event.kind === "free_agent"
          ? "freeAgent"
          : "gavel",
    eyebrow,
    title,
    // Only fires on a bid big enough to be worth a sentence. A $1 claim gets
    // the number and no commentary, because there is nothing to say about it.
    line: bid !== null && bid >= 20 ? voice.pick(BIG_BID_LINES) : null,
    chips: chip ? [chip] : [],
    moves,
    stats,
    href: transactionsHref(ctx, event),
    hrefLabel: "Open in transactions",
  };
}

