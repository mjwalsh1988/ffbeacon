function lineupCard(
  base: ActivityCard,
  event: ActivityEvent,
  ctx: ActivityContext,
  voice: Voice,
): ActivityCard {
  const p = event.payload as { rosterId?: number; started?: string[]; benched?: string[] };
  const rosterId = typeof p.rosterId === "number" ? p.rosterId : null;
  const chip = rosterId != null ? chipFor(ctx, rosterId) : null;
  const started = Array.isArray(p.started) ? p.started : [];
  const benched = Array.isArray(p.benched) ? p.benched : [];

  const moves: ActivityAsset[] = [
    ...started.map((id) => playerAsset(ctx, id, "in")),
    ...benched.map((id) => playerAsset(ctx, id, "out")),
  ];

  const who = chip?.label ?? "A team";
  const title =
    started.length > 0 && benched.length > 0
      ? `${who} started ${listOf(started.map((id) => playerName(ctx, id)))} over ${listOf(
          benched.map((id) => playerName(ctx, id)),
        )}`
      : started.length > 0
        ? `${who} moved ${listOf(started.map((id) => playerName(ctx, id)))} into the lineup`
        : `${who} benched ${listOf(benched.map((id) => playerName(ctx, id)))}`;

  return {
    ...base,
    accent: "amber",
    icon: "lineup",
    eyebrow: "Lineup change",
    title,
    line: voice.pick(LINEUP_LINES),
    chips: chip ? [chip] : [],
    moves,
    href: teamHref(ctx, rosterId),
    hrefLabel: chip ? `Open ${chip.label}` : null,
  };
}

function reserveCard(
  base: ActivityCard,
  event: ActivityEvent,
  ctx: ActivityContext,
): ActivityCard {
  const p = event.payload as {
    rosterId?: number;
    toReserve?: string[];
    fromReserve?: string[];
    toTaxi?: string[];
    fromTaxi?: string[];
  };
  const rosterId = typeof p.rosterId === "number" ? p.rosterId : null;
  const chip = rosterId != null ? chipFor(ctx, rosterId) : null;
  const toReserve = Array.isArray(p.toReserve) ? p.toReserve : [];
  const fromReserve = Array.isArray(p.fromReserve) ? p.fromReserve : [];
  const toTaxi = Array.isArray(p.toTaxi) ? p.toTaxi : [];
  const fromTaxi = Array.isArray(p.fromTaxi) ? p.fromTaxi : [];

  const moves: ActivityAsset[] = [
    ...toReserve.map((id) => labelledAsset(ctx, id, "out", "To IR")),
    ...fromReserve.map((id) => labelledAsset(ctx, id, "in", "Off IR")),
    ...toTaxi.map((id) => labelledAsset(ctx, id, "out", "To taxi")),
    ...fromTaxi.map((id) => labelledAsset(ctx, id, "in", "Off taxi")),
  ];

  const phrases: string[] = [];
  if (toReserve.length) phrases.push(`${listOf(toReserve.map((id) => playerName(ctx, id)))} to IR`);
  if (fromReserve.length)
    phrases.push(`${listOf(fromReserve.map((id) => playerName(ctx, id)))} off IR`);
  if (toTaxi.length) phrases.push(`${listOf(toTaxi.map((id) => playerName(ctx, id)))} to the taxi squad`);
  if (fromTaxi.length)
    phrases.push(`${listOf(fromTaxi.map((id) => playerName(ctx, id)))} off the taxi squad`);

  const who = chip?.label ?? "A team";
  const title = `${who} moved ${listOf(phrases)}`;

  return {
    ...base,
    accent: "amber",
    icon: "shield",
    eyebrow: "Roster status",
    title,
    chips: chip ? [chip] : [],
    moves,
    href: teamHref(ctx, rosterId),
    hrefLabel: chip ? `Open ${chip.label}` : null,
  };
}

function scoringCard(base: ActivityCard, event: ActivityEvent): ActivityCard {
  const changes = readChanges(event.payload).map(
    (c): ActivityChange => ({
      label: scoringLabel(c.key),
      from: scoringValue(c.from),
      to: scoringValue(c.to),
      direction: direction(c.from, c.to),
    }),
  );

  return {
    ...base,
    accent: "rose",
    icon: "scoring",
    eyebrow: "Scoring settings",
    title:
      changes.length === 1
        ? `${changes[0].label} changed`
        : `${changes.length} scoring rules changed`,
    changes,
    // Not decoration. Scoring is the input to every value, projection and
    // ranking on the rest of this page, and a reader comparing a number from
    // last week to one from this week deserves to be told why they moved.
    footnote:
      "Scoring drives every projection and value on this league's pages. Numbers from before this change are not comparable with the ones after it.",
  };
}

function rosterSlotsCard(base: ActivityCard, event: ActivityEvent): ActivityCard {
  const p = event.payload as {
    added?: string[];
    removed?: string[];
    fromCount?: number;
    toCount?: number;
  };
  const added = Array.isArray(p.added) ? p.added : [];
  const removed = Array.isArray(p.removed) ? p.removed : [];

  const moves: ActivityAsset[] = [
    ...added.map((slot, i) => ({
      key: `add-${slot}-${i}`,
      label: slotLabel(slot),
      detail: "Slot added",
      position: slot,
      direction: "in" as const,
    })),
    ...removed.map((slot, i) => ({
      key: `rm-${slot}-${i}`,
      label: slotLabel(slot),
      detail: "Slot removed",
      position: slot,
      direction: "out" as const,
    })),
  ];

  const stats: ActivityStat[] = [];
  if (typeof p.fromCount === "number" && typeof p.toCount === "number") {
    stats.push({
      label: "Roster size",
      value: `${p.fromCount} to ${p.toCount}`,
      tone: "neutral",
    });
  }

  const title =
    added.length > 0 && removed.length > 0
      ? `Roster slots changed, ${added.length} added and ${removed.length} removed`
      : added.length > 0
        ? `${listOf(added.map(slotLabel))} added to every roster`
        : `${listOf(removed.map(slotLabel))} removed from every roster`;

  return {
    ...base,
    accent: "rose",
    icon: "slots",
    eyebrow: "Roster makeup",
    title,
    moves,
    stats,
    footnote:
      "Roster shape decides which positions this league actually needs, so Positional WAR and Power Pulse both rebuild from here.",
  };
}

function teamCountCard(base: ActivityCard, event: ActivityEvent): ActivityCard {
  const p = event.payload as { from?: number | null; to?: number | null };
  const from = p.from ?? null;
  const to = p.to ?? null;
  const grew = from !== null && to !== null && to > from;

  return {
    ...base,
    accent: "rose",
    icon: "teams",
    eyebrow: "League size",
    title:
      from !== null && to !== null
        ? `League went from ${from} teams to ${to}`
        : "Team count changed",
    changes: [
      {
        label: "Teams",
        from: from === null ? "Unknown" : String(from),
        to: to === null ? "Unknown" : String(to),
        direction: grew ? "up" : "down",
      },
    ],
  };
}

