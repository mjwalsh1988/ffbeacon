function managerCard(
  base: ActivityCard,
  event: ActivityEvent,
  ctx: ActivityContext,
): ActivityCard {
  const p = event.payload as {
    displayName?: string | null;
    teamName?: string | null;
    rosterId?: number | null;
  };
  const joined = event.kind === "manager_joined";
  // The handle, not the team name: a team name changes on a whim and the handle
  // does not, and a manager who has just left cannot be looked up by a nickname.
  const who = p.displayName ? `@${p.displayName}` : (p.teamName ?? "A manager");
  const rosterId = typeof p.rosterId === "number" ? p.rosterId : null;
  const chip = rosterId != null ? chipFor(ctx, rosterId) : null;

  return {
    ...base,
    accent: joined ? "emerald" : "rose",
    icon: joined ? "userPlus" : "userMinus",
    eyebrow: joined ? "Manager joined" : "Manager left",
    title: joined ? `${who} joined the league` : `${who} is no longer in the league`,
    chips: chip ? [chip] : [],
    href: joined ? teamHref(ctx, rosterId) : null,
    hrefLabel: joined && chip ? `Open ${chip.label}` : null,
  };
}

