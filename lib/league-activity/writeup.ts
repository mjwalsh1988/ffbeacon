/**
 * The parts of a card that do not depend on what happened.
 *
 * Timing is settled here, once, so no card can invent its own convention. There
 * are three cases and they are genuinely different:
 *
 *   EXACT      Sleeper timestamped it. Print the time.
 *   RESULT     We know the week and nothing finer, so the week IS the time and
 *              no clock is printed at all.
 *   OBSERVED   We watched it happen inside a window. Say "spotted", and put the
 *              window itself in a note rather than picking a moment inside it.
 */
function emptyCard(event: ActivityEvent, ctx: ActivityContext): ActivityCard {
  const isResult = event.kind === "matchup_result";
  const exact = event.precision === "exact";
  // A RESULT'S TIMESTAMP IS DERIVED FROM ITS WEEK, so a game that settles before
  // its synthetic Tuesday sits slightly in the future and `formatRelative` would
  // render "in 2 days" on a card whose whole point is that the game is over.
  // The week label already says everything we actually know, so the relative
  // phrase is simply dropped rather than made up.
  const relative =
    Date.parse(event.occurredAt) > ctx.nowMs
      ? ""
      : formatRelative(event.occurredAt, ctx.nowMs);

  const timeLabel = isResult
    ? event.week != null
      ? `Week ${event.week}`
      : "Final"
    : exact
      ? formatEastern(event.occurredAt)
      : `Spotted ${formatEastern(event.occurredAt)}`;

  const timeNote =
    !exact && !isResult && event.observedFrom
      ? `Sleeper does not timestamp this kind of change, so all we can say is that it happened between ${formatEastern(
          event.observedFrom,
        )} and ${formatEastern(event.occurredAt)}.`
      : null;

  return {
    id: event.id,
    kind: event.kind,
    category: ACTIVITY_CATEGORY_OF[event.kind],
    accent: "slate",
    icon: "settings",
    eyebrow: "Activity",
    title: "Something changed",
    line: null,
    occurredAtIso: event.occurredAt,
    timeLabel,
    timeRelative: relative,
    timeNote,
    // A result puts its week in the time slot, so repeating it as a badge would
    // print "Week 6" twice on the same row.
    weekLabel: !isResult && event.week != null ? `Week ${event.week}` : null,
    chips: [],
    columns: [],
    moves: [],
    stats: [],
    changes: [],
    footnote: null,
    href: null,
    hrefLabel: null,
  };
}

function chipFor(ctx: ActivityContext, rosterId: number): ActivityChip {
  const team = ctx.teams[rosterId];
  return {
    rosterId,
    label: team?.label ?? `Team ${rosterId}`,
    owner: team?.owner ?? null,
    avatarId: team?.avatarId ?? null,
    tone: "neutral",
    href: teamHref(ctx, rosterId),
  };
}

function playerName(ctx: ActivityContext, id: string): string {
  return ctx.players[id]?.name ?? `Player ${id}`;
}

function playerAsset(
  ctx: ActivityContext,
  id: string,
  direction: "in" | "out",
): ActivityAsset {
  const p = ctx.players[id];
  // "RB, ATL" rather than a separator character. See CLAUDE.md: no middle dots.
  const detail = p
    ? [p.position, p.team].filter(Boolean).join(", ") || null
    : "Player no longer in our database";
  return {
    key: `${direction}-${id}`,
    label: p?.name ?? `Player ${id}`,
    detail,
    position: p?.position ?? null,
    direction,
  };
}

function labelledAsset(
  ctx: ActivityContext,
  id: string,
  direction: "in" | "out",
  detail: string,
): ActivityAsset {
  return { ...playerAsset(ctx, id, direction), detail };
}

function pickAsset(
  pick: { season: number; round: number; originalRosterId: number | null },
  direction: "in" | "out",
): ActivityAsset {
  return {
    key: `${direction}-pick-${pick.season}-${pick.round}-${pick.originalRosterId ?? "x"}`,
    label: pickLabel(pick.season, pick.round),
    detail: "Draft pick",
    position: "PICK",
    direction,
  };
}

/** One decimal, always, so a column of scores lines up. */
function points(value: number): string {
  return Number.isFinite(value) ? value.toFixed(1) : "0.0";
}

function direction(from: unknown, to: unknown): "up" | "down" | "flat" {
  const a = Number(from);
  const b = Number(to);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return "flat";
  if (b > a) return "up";
  if (b < a) return "down";
  return "flat";
}

function asText(value: unknown): string | null {
  if (value === null || value === undefined) return null;
  const s = String(value).trim();
  return s ? s : null;
}

function readChanges(
  payload: Record<string, unknown>,
): Array<{ key: string; from: unknown; to: unknown }> {
  const raw = payload.changes;
  if (!Array.isArray(raw)) return [];
  return raw
    .filter((c): c is { key: string; from: unknown; to: unknown } => {
      return Boolean(c) && typeof (c as { key?: unknown }).key === "string";
    })
    .map((c) => ({ key: c.key, from: c.from, to: c.to }));
}

function readSides(payload: Record<string, unknown>): Array<{
  rosterId: number;
  players: string[];
  picks: Array<{ season: number; round: number; originalRosterId: number | null }>;
  faab: number;
}> {
  const raw = payload.sides;
  if (!Array.isArray(raw)) return [];
  return raw
    .map((s) => {
      const side = (s ?? {}) as Record<string, unknown>;
      const rosterId = Number(side.rosterId);
      if (!Number.isFinite(rosterId)) return null;
      return {
        rosterId,
        players: Array.isArray(side.players)
          ? side.players.filter((p): p is string => typeof p === "string")
          : [],
        picks: Array.isArray(side.picks)
          ? side.picks
              .map((p) => {
                const pick = (p ?? {}) as Record<string, unknown>;
                const season = Number(pick.season);
                const round = Number(pick.round);
                if (!Number.isFinite(season) || !Number.isFinite(round)) return null;
                const original = Number(pick.originalRosterId);
                return {
                  season,
                  round,
                  originalRosterId: Number.isFinite(original) ? original : null,
                };
              })
              .filter(
                (
                  p,
                ): p is { season: number; round: number; originalRosterId: number | null } =>
                  p !== null,
              )
          : [],
        faab: Number.isFinite(Number(side.faab)) ? Number(side.faab) : 0,
      };
    })
    .filter(
      (
        s,
      ): s is {
        rosterId: number;
        players: string[];
        picks: Array<{ season: number; round: number; originalRosterId: number | null }>;
        faab: number;
      } => s !== null,
    );
}

