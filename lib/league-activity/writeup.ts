function withUsername(path: string, ctx: ActivityContext, extra?: URLSearchParams): string {
  const qs = extra ?? new URLSearchParams();
  if (ctx.searchedUsername) qs.set("username", ctx.searchedUsername);
  const s = qs.toString();
  return s ? `${path}?${s}` : path;
}

/**
 * Where a transaction card points.
 *
 * The feed shows what moved; the transactions page shows what it was WORTH,
 * because that is where Signal Check's graded card already lives. Deliberately
 * filtered to the event's own type and week so the reader lands on a short list
 * containing their row rather than on page one of the season.
 */
function transactionsHref(ctx: ActivityContext, event: ActivityEvent): string {
  const qs = new URLSearchParams();
  // The transactions page filters on `league_transactions.type`, which is
  // Sleeper's raw string. Our kind is the same word for the four types we know
  // and is "commissioner_move" for anything else, so a card built from an
  // unrecognised type would have linked to an empty list. The payload keeps the
  // original when it differs.
  const stored =
    typeof event.payload.sleeperType === "string" && event.payload.sleeperType
      ? event.payload.sleeperType
      : null;
  const type =
    stored ?? (event.kind === "commissioner_move" ? "commissioner" : (event.kind as string));
  qs.set("type", type);
  if (event.week != null) qs.set("week", String(event.week));
  return withUsername(`/leagues/${ctx.sleeperLeagueId}/transactions`, ctx, qs);
}

function matchupHref(
  ctx: ActivityContext,
  event: ActivityEvent,
  rosterId: number,
): string | null {
  if (event.week == null) return null;
  return withUsername(
    `/leagues/${ctx.sleeperLeagueId}/schedules/${event.week}/${rosterId}`,
    ctx,
  );
}

function teamHref(ctx: ActivityContext, rosterId: number | null): string | null {
  if (rosterId == null) return null;
  return withUsername(`/leagues/${ctx.sleeperLeagueId}/teams/${rosterId}`, ctx);
}

