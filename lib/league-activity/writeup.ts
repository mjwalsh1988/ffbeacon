/**
 * From an event to a card.
 *
 * Pure. It takes one stored event plus the league's CURRENT identities and
 * returns everything the component draws. No database, no clock of its own (the
 * caller fixes `nowMs`, so one page cannot say "2 hours ago" in one card and
 * "3 hours ago" in the next), and no Discord.
 *
 * THE VOICE IS THE RELAY'S VOICE, deliberately. `lib/league-relay/voice.ts` is
 * imported rather than copied, so a line here obeys the same rule every line in
 * a Discord post obeys: EVERY SENTENCE CITES A FIGURE THAT IS ON THE SAME CARD.
 * The joke is in the framing of a number, never in a claim beside it, and
 * nothing is generated by a language model. A reader has to be able to check
 * the sentence against the stat block under it.
 *
 * The draw is seeded on the event's own id, so a card reads the same on every
 * render. A feed whose wording shuffled on refresh would be unreadable, and a
 * reader who scrolled past something funny could never find it again.
 *
 * WHAT THIS FILE WILL NOT DO IS PRINT A NUMBER IT WAS NOT GIVEN. A null bench
 * total means the stat is omitted, not zeroed. A lineup change we watched
 * across a window says it was spotted, and shows the window. An approximate
 * ordering timestamp on a result is never rendered as a clock time.
 */

