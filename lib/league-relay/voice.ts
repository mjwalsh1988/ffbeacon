/**
 * How a team is doing, in five bands, from its rank within its own league.
 *
 * A rank rather than a raw score, because a 78 Power Pulse is excellent in one
 * league and mid-table in another, and the reader only cares about the room
 * they are in.
 */
export type Band = "elite" | "good" | "middle" | "poor" | "dire";

export function bandFromRank(rank: number | null, total: number): Band {
  if (rank === null || total <= 1) return "middle";
  const q = (rank - 1) / (total - 1);
  if (q <= 0.15) return "elite";
  if (q <= 0.4) return "good";
  if (q <= 0.6) return "middle";
  if (q <= 0.85) return "poor";
  return "dire";
}

