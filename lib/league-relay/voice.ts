/**
 * The relay's voice.
 *
 * The brief is a writeup, not a bullet list: sarcastic, hyperbolic, funny, and
 * still worth reading for the numbers. Those two goals fight, and the way this
 * module settles the fight is the only interesting thing in it:
 *
 *   EVERY SENTENCE CITES A FIGURE THAT IS ON THE SAME SCREEN. The joke is in
 *   the FRAMING of the number, never in a claim beside it. "Wow, this team
 *   sucks" is not sayable on its own; "the worst projected lineup in the
 *   league, 14.2 points behind eleventh" is, and it is funnier for being true.
 *
 *   NOTHING HERE IS GENERATED BY A LANGUAGE MODEL. Same rule as Signal Check's
 *   reasons (see CLAUDE.md, Trade Ideas): a reader must be able to check every
 *   sentence against the numbers printed under it, which a generated one does
 *   not allow. These are hand-written templates chosen by a seeded draw.
 *
 * WHY THE DRAW IS SEEDED. The same trade must read the same way every time it
 * is rendered: the admin preview has to show what the channel will get, a retry
 * after a Discord 500 must not post a differently-worded second version, and a
 * ledger row has to match what went out. So the seed is the message's own
 * dedupe key, and variety comes from there being many keys, not from a clock.
 *
 * SNARK IS A DIAL, NOT A SWITCH. `snark` runs 0 to 1. Each line carries the
 * heat it needs; a line hotter than the setting is simply not drawn, so turning
 * the dial down yields a straight report built from the same figures rather
 * than a different feature.
 */

/** A line, and how sharp it is. Drawn only when `snark` is at least `heat`. */
export interface Line {
  /** 0 is a neutral statement of fact. 1 is at somebody's expense. */
  heat: number;
  text: string;
}

/* -------------------------------------------------------------------------- */
/* Seeded selection                                                           */
/* -------------------------------------------------------------------------- */

/** FNV-1a. Small, fast, and stable across runtimes, which is the requirement. */
export function seedFrom(key: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < key.length; i += 1) {
    h ^= key.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/**
 * A deterministic draw over a seed.
 *
 * mulberry32: one line of arithmetic, uniform enough for choosing between eight
 * phrasings, and identical on every machine. `Math.random` would break the
 * guarantee in the header.
 */
export function makeRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * A writer, bound to one message.
 *
 * Holds the seed and the snark setting so a builder can ask for a line without
 * threading either through every call.
 */
export class Voice {
  private rng: () => number;
  /**
   * Every line this writer has already used.
   *
   * A message describes two teams, and the two draws are independent, so
   * nothing stopped both of them landing on the same phrase. The first real run
   * produced a preview whose two closing lines were "actively bad in a way that
   * is starting to look deliberate", twice, one under the other. That does not
   * read as a coincidence, it reads as a broken template.
   */
  private used = new Set<string>();

  constructor(
    seedKey: string,
    /** 0 to 1. */
    public readonly snark: number,
  ) {
    this.rng = makeRng(seedFrom(seedKey));
  }

  /** A number in [0, 1). Advances the sequence, so call order matters. */
  next(): number {
    return this.rng();
  }

  /**
   * Draw one line from a bank, honouring the snark setting.
   *
   * Lines hotter than the setting are filtered out FIRST, so lowering the dial
   * changes which lines are eligible rather than merely how often a hot one is
   * picked. Returns null when the bank has nothing cool enough, which is a
   * legitimate outcome: the section is simply not written.
   *
   * A line already used in this message is skipped, unless skipping would leave
   * nothing at all. Repeating beats staying silent; repeating by accident does
   * not.
   */
  pick(bank: Line[]): string | null {
    const eligible = bank.filter((l) => l.heat <= this.snark);
    if (eligible.length === 0) return null;
    const unused = eligible.filter((l) => !this.used.has(l.text));
    const pool = unused.length > 0 ? unused : eligible;
    const chosen = pool[Math.floor(this.rng() * pool.length)].text;
    this.used.add(chosen);
    return chosen;
  }

  /** Draw from a plain list of strings, all at heat 0. */
  pickPlain(bank: string[]): string {
    const unused = bank.filter((t) => !this.used.has(t));
    const pool = unused.length > 0 ? unused : bank;
    const chosen = pool[Math.floor(this.rng() * pool.length)];
    this.used.add(chosen);
    return chosen;
  }
}

/* -------------------------------------------------------------------------- */
/* Number formatting the writeups share                                       */
/* -------------------------------------------------------------------------- */

export function pct(value: number | null | undefined, digits = 0): string | null {
  if (value === null || value === undefined || !Number.isFinite(value)) return null;
  return `${(value * 100).toFixed(digits)}%`;
}

/** A signed percentage-point change: "+12 points", "-4 points". */
export function ppChange(
  before: number | null | undefined,
  after: number | null | undefined,
): { text: string; delta: number } | null {
  if (before === null || before === undefined || after === null || after === undefined) return null;
  if (!Number.isFinite(before) || !Number.isFinite(after)) return null;
  const delta = (after - before) * 100;
  if (Math.abs(delta) < 0.5) return { text: "no meaningful change", delta: 0 };
  const sign = delta > 0 ? "+" : "";
  return { text: `${sign}${delta.toFixed(0)} points`, delta };
}

export function signed(value: number, digits = 1): string {
  const sign = value > 0 ? "+" : value < 0 ? "" : "";
  return `${sign}${value.toFixed(digits)}`;
}

export function num(value: number | null | undefined, digits = 1): string | null {
  if (value === null || value === undefined || !Number.isFinite(value)) return null;
  return value.toFixed(digits);
}

