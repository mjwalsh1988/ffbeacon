/**
 * The band as a phrase, with the hyperbole applied when the dial allows it and
 * the plain adjective when it does not. Never returns nothing: every writeup
 * needs to be able to describe a team.
 */
export function describeBand(voice: Voice, band: Band): string {
  return voice.pick(BAND_LINES[band]) ?? BAND_PLAIN[band];
}

