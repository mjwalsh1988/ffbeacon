-- Migration 0364: long_shot_puzzles (one row per Eastern game date for Long
-- Shot, the daily rarity game). Plan: docs/completed/long-shot/long-shot-plan.md 15.2.
--
-- Access matrix:
--   anon          : none
--   authenticated : none
--   service_role  : ALL (generate cron, inline generation, admin, settle cron)
--   client writes : BLOCKED
--
-- No client policy of any kind: a puzzle row is only ever read server-side.
-- game_date is unique, so a race between the cron and inline generation for
-- the same date surfaces as 23505 and is read as "someone else generated it".

create table if not exists public.long_shot_puzzles (
  id uuid primary key default gen_random_uuid(),
  game_date date not null unique,
  status text not null default 'ready' check (status in ('ready','short')),
  prompt_count integer not null check (prompt_count between 1 and 5),
  seed_salt integer not null default 0 check (seed_salt >= 0),
  generated_at timestamptz not null default now(),
  generated_by text not null check (generated_by in ('cron','inline','admin')),
  settled_at timestamptz,
  completed_attempts integer not null default 0 check (completed_attempts >= 0),
  model_version integer not null default 1
);

alter table public.long_shot_puzzles enable row level security;

drop policy if exists long_shot_puzzles_service_role_all on public.long_shot_puzzles;
create policy long_shot_puzzles_service_role_all on public.long_shot_puzzles
  for all to service_role using (true) with check (true);

revoke all on public.long_shot_puzzles from anon, authenticated;

comment on table public.long_shot_puzzles is
  'One Long Shot puzzle per Eastern game date. Service-role only. Generated by /api/cron/long-shot-generate, inline by the attempt route, or by an admin regenerate.';
